def _glsl_float(value: float) -> str:
    text = f"{float(value):.10g}"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


def _summarize_dispatch_value(value):
    if isinstance(value, Gm45Tensor):
        return {
            "kind": "Gm45Tensor",
            "shape": list(value.shape),
            "dtype": str(value.dtype),
            "device": str(value.device),
            "texture": value._owner.texture,
            "storage": value._owner.layout.kind,
            "storage_offset": value._storage_offset,
            "logical_strides": list(value._logical_strides),
        }
    if isinstance(value, torch.Tensor):
        return {
            "kind": "torch.Tensor",
            "shape": list(value.shape),
            "dtype": str(value.dtype),
            "device": str(value.device),
        }
    if isinstance(value, (list, tuple)):
        return [_summarize_dispatch_value(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _summarize_dispatch_value(v) for k, v in value.items()}
    if isinstance(value, (int, float, bool, str, type(None))):
        return value
    return repr(value)


def _record_unsupported(func, args, kwargs) -> None:
    name = str(func)
    _unsupported_counts[name] += 1
    if len(_unsupported_examples[name]) < 3:
        _unsupported_examples[name].append(
            {
                "args": _summarize_dispatch_value(args),
                "kwargs": _summarize_dispatch_value(kwargs or {}),
            }
        )


def reset_unsupported_report() -> None:
    _unsupported_counts.clear()
    _unsupported_examples.clear()


def unsupported_report() -> dict[str, dict]:
    return {
        name: {"calls": count, "examples": _unsupported_examples.get(name, [])}
        for name, count in sorted(_unsupported_counts.items())
    }


