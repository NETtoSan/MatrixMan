def _register_privateuse_name() -> None:
    try:
        torch.utils.rename_privateuse1_backend("gm45")
    except RuntimeError as exc:
        # PyTorch allows this once per process. Re-importing this module in the
        # same process is fine if the name is already correct.
        current = torch._C._get_privateuse1_backend_name()
        if current != "gm45":
            raise RuntimeError(f"PrivateUse1 is already registered as {current!r}, not 'gm45'") from exc

    class BackendModule:
        @staticmethod
        def is_available() -> bool:
            return _runtime is not None

        @staticmethod
        def device_count() -> int:
            return 1

        @staticmethod
        def current_device() -> int:
            return 0

        @staticmethod
        def is_initialized() -> bool:
            return _runtime is not None

        @staticmethod
        def _is_in_bad_fork() -> bool:
            return False

        @staticmethod
        def manual_seed_all(seed: int) -> None:
            del seed
            # MatrixMan currently has no device-side RNG.
            return None

    try:
        torch._register_device_module("privateuseone", BackendModule)
    except RuntimeError as exc:
        if not hasattr(torch, "gm45"):
            raise


