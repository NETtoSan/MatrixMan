#!/usr/bin/env python3
"""
Experimental PyTorch-facing GM45 backend prototype.

This is deliberately small and strict:

  supported:
    - CPU float32 1D, 2D, 3D, or 4D NCHW tensor -> gm45 tensor
    - gm45 tensor -> CPU tensor via .cpu() / .to("cpu")
    - metadata-only view/reshape/flatten/squeeze/unsqueeze
    - metadata-only split for contiguous batch-1 NCHW channel ranges
    - GPU copy/repack cat for packed batch-1 NCHW channel concatenation
    - max_pool2d values for the YOLO SPPF kernel=5/stride=1/padding=2 subset
    - nearest-neighbor 2x upsample for the traced YOLO NCHW inference subset
    - float32 1D arange factory values generated by a GLSL fragment shader
    - torch.add(gm45, gm45) for square 2D matrices or packed tensors with identical shapes
    - torch.matmul(gm45, gm45) for square 2D matrices

  unsupported:
    - everything else, with a clear error

The tensor payload is a persistent OpenGL RGBA32F texture. Chained operations
like D = torch.add(torch.matmul(A, B), A) remain texture -> shader -> texture
until the user explicitly calls .cpu().

This is not a production PrivateUse1 C++ backend yet. It uses PyTorch's
PrivateUse1 naming plus a Tensor wrapper subclass as the minimum runnable
experiment before implementing OpaqueTensorImpl/custom storage in C++.
"""

